"""Enterprise spend limits, account switches, and the plan message.

Every profile and payload here is built by the test. The real ~/.claude.json
holds per-project history for every directory Claude Code has opened, and a
captured copy would carry it into a public repository (CLAUDE.md, "Fixtures
are generated by committed code").
"""
import json
import os

from pc import claude_account, ingest, normalizer, protocol
from pc import statusline_source as ss
from pc.bridge import Bridge
from pc.providers import base

NOW = 1_787_700_000.0


# ------------------------------------------------------------------ helpers

def write_profile(path, org_type="claude_max", account="acct-1", org="org-1"):
    doc = {"numStartups": 3, "projects": {"/somewhere": {"history": []}},
           "oauthAccount": {"accountUuid": account, "organizationUuid": org,
                            "organizationType": org_type,
                            "emailAddress": "someone@example.invalid"}}
    with open(path, "w", encoding="utf-8") as f:
        json.dump(doc, f)


def windows(observed_at, src="cli", session=40.0, weekly=20.0):
    return base.NormalizedUsageFrame(provider="claude", src=src,
                                     observed_at=observed_at,
                                     session_pct=session, weekly_pct=weekly)


def spend(observed_at, pct=62.8, usd=314.12, limit=500.0, period="monthly"):
    return base.NormalizedUsageFrame(
        provider="claude", src="cli", observed_at=observed_at,
        session_pct=pct, session_resets_at=NOW + 20 * 86400,
        plan=base.PLAN_SPEND, spend_usd=usd, spend_limit_usd=limit,
        spend_period=period)


def hook_state(observed_at):
    return base.NormalizedUsageFrame(provider="claude", src="hook",
                                     observed_at=observed_at,
                                     state=base.STATE_RUNNING, n_run=1)


def spend_payload(**over):
    w = {"used_percentage": 62.8, "resets_at": NOW + 20 * 86400,
         "used_usd": 314.12, "limit_usd": 500, "period": "monthly"}
    w.update(over)
    return {"rate_limits": {"spend_limit": w}}


# ------------------------------------------------- reading Claude Code's line

def test_a_spend_limit_becomes_a_spend_frame():
    f = ss.map_statusline_frame(spend_payload(), NOW, NOW - 5)
    assert f.plan == base.PLAN_SPEND
    assert f.session_pct == 62.8
    assert f.session_resets_at == NOW + 20 * 86400
    assert f.weekly_pct == base.UNKNOWN
    assert (f.spend_usd, f.spend_limit_usd, f.spend_period) == (
        314.12, 500.0, "monthly")


def test_the_dollars_are_optional_and_the_percentage_is_not():
    """Claude Code sends the percentage first and the dollars about five
    minutes later, and never under CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC."""
    p = {"rate_limits": {"spend_limit": {"used_percentage": 12.0,
                                         "resets_at": NOW + 3600}}}
    f = ss.map_statusline_frame(p, NOW, NOW)
    assert f.plan == base.PLAN_SPEND
    assert (f.spend_usd, f.spend_limit_usd, f.spend_period) == (None, None, "")

    p = {"rate_limits": {"spend_limit": {"used_usd": 3.0, "limit_usd": 9}}}
    assert ss.map_statusline_frame(p, NOW, NOW).plan == base.PLAN_WINDOWS


def test_nonsense_in_the_spend_object_is_not_drawn():
    p = spend_payload(used_usd=-4, limit_usd=float("nan"), period="hourly")
    f = ss.map_statusline_frame(p, NOW, NOW)
    assert (f.spend_usd, f.spend_limit_usd, f.spend_period) == (None, None, "")
    p = spend_payload(used_percentage=-1)
    assert ss.map_statusline_frame(p, NOW, NOW).plan == base.PLAN_WINDOWS
    p = {"rate_limits": {"spend_limit": "62%"}}
    assert ss.map_statusline_frame(p, NOW, NOW).plan == base.PLAN_WINDOWS


def test_spend_wins_over_windows_on_a_payload_carrying_both():
    p = spend_payload()
    p["rate_limits"]["five_hour"] = {"used_percentage": 90.0,
                                     "resets_at": NOW + 600}
    f = ss.map_statusline_frame(p, NOW, NOW)
    assert f.plan == base.PLAN_SPEND and f.session_pct == 62.8


def test_a_spend_period_that_rolled_over_is_zero_dollars_while_fresh():
    p = spend_payload(resets_at=NOW - 60)
    f = ss.map_statusline_frame(p, NOW, NOW - 120)
    assert f.session_pct == 0.0 and f.spend_usd == 0.0
    assert f.session_resets_at is None and f.session_rolled_at == NOW - 60
    # ...and unknown, not zero, once the reading is old.
    old = ss.map_statusline_frame(p, NOW, NOW - ss.STALE_AFTER_S - 1)
    assert old.session_pct == base.UNKNOWN and old.spend_usd is None


# ----------------------------------------------------------- the profile

def test_profile_kinds(tmp_path):
    p = tmp_path / ".claude.json"
    for org_type, kind in (("claude_max", "consumer"),
                           ("claude_pro", "consumer"),
                           ("claude_enterprise", "enterprise"),
                           ("claude_team", "team"),
                           ("something_new", "consumer")):
        write_profile(p, org_type)
        assert claude_account.read_profile(str(p))[0] == kind, org_type


def test_no_profile_is_no_answer(tmp_path):
    p = tmp_path / ".claude.json"
    assert claude_account.read_profile(str(p)) is None
    p.write_text("{not json", encoding="utf-8")
    assert claude_account.read_profile(str(p)) is None
    p.write_text(json.dumps({"numStartups": 1}), encoding="utf-8")
    assert claude_account.read_profile(str(p)) is None


def test_the_profile_follows_claude_config_dir(tmp_path, monkeypatch):
    monkeypatch.setenv("CLAUDE_CONFIG_DIR", str(tmp_path / "work"))
    assert claude_account.profile_path() == str(tmp_path / "work" /
                                                ".claude.json")
    monkeypatch.delenv("CLAUDE_CONFIG_DIR")
    assert claude_account.profile_path() == os.path.join(
        os.path.expanduser("~"), ".claude.json")


def _bump(path, t):
    os.utime(path, (t, t))


def test_a_switch_is_dated_when_seen_and_startup_is_not_a_switch(tmp_path):
    p = tmp_path / ".claude.json"
    write_profile(p, "claude_max", account="me")
    _bump(p, NOW - 100)
    w = claude_account.AccountWatch(str(p))
    w.poll(NOW)
    assert (w.kind, w.since) == ("consumer", None)

    # Claude Code rewriting its history is not a switch.
    write_profile(p, "claude_max", account="me")
    _bump(p, NOW - 50)
    w.poll(NOW + 2)
    assert w.since is None

    write_profile(p, "claude_enterprise", account="me-at-work", org="corp")
    _bump(p, NOW + 3)
    w.poll(NOW + 4)
    assert (w.kind, w.since, w.touched_at) == ("enterprise", NOW + 4, NOW + 3)


def test_an_unreadable_moment_changes_nothing(tmp_path):
    p = tmp_path / ".claude.json"
    write_profile(p, "claude_enterprise")
    w = claude_account.AccountWatch(str(p))
    w.poll(NOW)
    p.write_text("{half-writ", encoding="utf-8")
    _bump(p, NOW + 9)
    w.poll(NOW + 10)
    assert (w.kind, w.since) == ("enterprise", None)


