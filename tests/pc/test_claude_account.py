def test_a_merged_spend_page_keeps_its_dollars_together():
    m = normalizer.merge([spend(NOW - 10), hook_state(NOW)])
    assert (m.plan, m.session_pct, m.spend_usd, m.spend_limit_usd,
            m.spend_period) == (base.PLAN_SPEND, 62.8, 314.12, 500.0,
                                "monthly")
    assert m.state == base.STATE_RUNNING


def test_an_unreported_page_survives_the_merge():
    frames = claude_account.select([hook_state(NOW)], "enterprise",
                                   now_epoch=NOW)
    m = normalizer.merge(frames)
    assert m is not None
    assert (m.plan, m.account, m.session_pct) == (
        base.PLAN_UNREPORTED, "enterprise", base.UNKNOWN)


# --------------------------------------------------------- the wire

def test_the_plan_message():
    assert protocol.plan() == {"t": "plan", "v": protocol.VERSION}
    m = protocol.plan_for(normalizer.merge([spend(NOW)]))
    assert m == {"t": "plan", "v": protocol.VERSION, "provider": "claude",
                 "plan": "spend", "period": "monthly", "usd": 314.12,
                 "lim": 500.0}
    u = protocol.plan("claude", base.PLAN_UNREPORTED, account="enterprise")
    assert u["acct"] == "enterprise" and "usd" not in u
    assert protocol.plan_for(normalizer.merge([windows(NOW)])) == \
        protocol.plan()


def test_the_plan_names_claude_when_codex_holds_the_outer_ring():
    codex = base.NormalizedUsageFrame(provider="codex", src="cli",
                                      observed_at=NOW, session_pct=5.0)
    m = protocol.plan_for(codex, normalizer.merge([spend(NOW)]))
    assert m["provider"] == "claude"


def test_a_spend_countdown_is_not_clamped_to_twelve_days():
    msg = protocol.frame_to_usage(spend(NOW), NOW)
    assert msg["session_resets_in_s"] == 20 * 86400
    assert msg["weekly_pct"] == base.UNKNOWN
    assert msg["weekly_resets_in_s"] == -1
    far = spend(NOW)
    far.session_resets_at = NOW + 400 * 86400
    assert protocol.frame_to_usage(far, NOW)["session_resets_in_s"] == \
        protocol.SPEND_COUNTDOWN_MAX_S


def test_the_widest_spend_line_fits():
    """The usage line's budget is decided on the two-provider line (see
    test_protocol's widest line). A spend page swaps a seven-day countdown
    for -1 and gains one digit on the session countdown, so it can only be
    shorter; this checks it rather than trusting the arithmetic."""
    def widest(provider, **kw):
        return base.NormalizedUsageFrame(
            provider=provider, src="cli-state",
            observed_at=NOW - 2147483647, active_at=NOW - 2147483647,
            session_pct=102.33333333333333,
            session_resets_at=NOW + 31536000.1234567,
            state="running", stale=False, n_run=99, n_wait=99, n_stuck=99,
            n_idle=99, n_agents=99, **kw)
    s = widest("claude", plan=base.PLAN_SPEND, spend_usd=99999.99,
               spend_limit_usd=99999.99, spend_period="monthly")
    c = widest("codex", weekly_pct=102.6666, weekly_resets_at=NOW + 3e7,
               session_burn_pph=999.9)
    for primary, secondary in ((s, c), (c, s)):
        raw, why = protocol.encode_checked(
            protocol.frame_to_usage(primary, NOW, secondary))
        assert why is None, why
    raw, why = protocol.encode_checked(protocol.plan_for(s))
    assert why is None


def test_old_firmware_gets_dashes_not_a_mislabelled_spend_share():
    plan = protocol.plan_for(normalizer.merge([spend(NOW)]))
    usage = protocol.frame_to_usage(normalizer.merge([spend(NOW)]), NOW)
    for fw in (None, "1.3.5", "junk"):
        out = protocol.hide_plan_for_fw(usage, plan, fw)
        assert out["session_pct"] == base.UNKNOWN
        assert out["session_resets_in_s"] == -1
    assert usage["session_pct"] == 62.8          # not mutated
    assert protocol.hide_plan_for_fw(usage, plan, "1.4.0") == usage
    assert protocol.hide_plan_for_fw(usage, protocol.plan(), None) == usage


def test_old_firmware_hiding_reaches_the_second_page_too():
    codex = base.NormalizedUsageFrame(provider="codex", src="cli",
                                      observed_at=NOW, session_pct=5.0)
    s = normalizer.merge([spend(NOW)])
    usage = protocol.frame_to_usage(codex, NOW, s)
    out = protocol.hide_plan_for_fw(usage, protocol.plan_for(codex, s),
                                    "1.3.5")
    assert out["session_pct"] == 5.0
    assert "p2_session_pct" not in out and "p2_s_in_s" not in out


# ------------------------------------------------------------- the bus

class Fixed:
    def __init__(self, *frames):
        self.frames = list(frames)

    def get_provider_id(self):
        return "claude"

    def poll(self, now):
        return list(self.frames)


class FakeAccount:
    def __init__(self, kind="", since=None, touched_at=None):
        self.kind, self.since, self.touched_at = kind, since, touched_at

    def poll(self, now):
        pass


def test_the_bus_shows_spend_and_says_so():
    bus = ingest.IngestionBus(providers=[Fixed(spend(NOW - 5))],
                              now=lambda: NOW, account=FakeAccount())
    msg = bus.poll()
    assert msg["session_pct"] == 62.8
    assert bus.plan_msg()["plan"] == "spend"


def test_the_bus_drops_the_old_account_at_a_switch():
    stale_max = windows(NOW - 120)
    bus = ingest.IngestionBus(providers=[Fixed(stale_max, hook_state(NOW))],
                              now=lambda: NOW,
                              account=FakeAccount("enterprise",
                                                  since=NOW - 60))
    msg = bus.poll()
    assert msg["session_pct"] == base.UNKNOWN
    assert bus.plan_msg() == protocol.plan("claude", "unreported",
                                           account="enterprise")


def test_a_scenario_bus_does_not_read_this_desks_account():
    bus = ingest.IngestionBus(providers=[], now=lambda: NOW)
    assert bus._account is None


def test_an_account_that_raises_costs_nothing():
    class Boom(FakeAccount):
        def poll(self, now):
            raise OSError("gone")
    bus = ingest.IngestionBus(providers=[Fixed(windows(NOW))],
                              now=lambda: NOW, account=Boom())
    assert bus.poll()["session_pct"] == 40.0


# ----------------------------------------------------------- the bridge

class _Fetch:
    def __init__(self, usage, plan):
        self.usage, self.plan = usage, plan

    def __call__(self):
        return self.usage

    def plan_msg(self):
        return self.plan


def _bridge(fetch, sent, fw=None):
    b = Bridge(write_msg=sent.append, fetch_usage=fetch, now=lambda: 0.0,
               wall=lambda: (int(NOW), 0))
    b._board_fw = fw
    return b


def test_the_plan_goes_out_before_the_usage_it_describes():
    sent = []
    s = normalizer.merge([spend(NOW)])
    fetch = _Fetch(protocol.frame_to_usage(s, NOW), protocol.plan_for(s))
    _bridge(fetch, sent, fw="1.4.0").poll_once()
    assert [m["t"] for m in sent] == ["time", "plan", "usage"]
    assert sent[2]["session_pct"] == 62.8


def test_the_plan_is_sent_on_change_and_again_on_every_connect():
    sent = []
    s = normalizer.merge([spend(NOW)])
    fetch = _Fetch(protocol.frame_to_usage(s, NOW), protocol.plan_for(s))
    b = _bridge(fetch, sent, fw="1.4.0")
    b.poll_once()
    b.poll_once()
    assert [m["t"] for m in sent].count("plan") == 1
    # New dollars, same percentage line: the fast tick still says so.
    fetch.plan = dict(fetch.plan, usd=318.0)
    b.poll_if_changed()
    assert sent[-1] == fetch.plan
    sent.clear()
    b.greet()
    assert "plan" in [m["t"] for m in sent]


def test_an_old_board_is_sent_dashes():
    sent = []
    s = normalizer.merge([spend(NOW)])
    fetch = _Fetch(protocol.frame_to_usage(s, NOW), protocol.plan_for(s))
    _bridge(fetch, sent, fw="1.3.5").poll_once()
    usage = [m for m in sent if m["t"] == "usage"][0]
    assert usage["session_pct"] == base.UNKNOWN


def test_switching_back_clears_the_plan_before_max_has_said_anything():
    """Every reading from before the switch is dropped and the Max login has
    not rendered yet, so there is no usage message -- but the board must
    still stop saying "Not reported" about the corporate account."""
    acct = FakeAccount("enterprise")
    stale = windows(NOW - 600)
    bus = ingest.IngestionBus(providers=[Fixed(stale)], now=lambda: NOW,
                              account=acct)
    sent = []
    b = _bridge(bus.fetch(), sent, fw="1.4.0")
    acct.since = NOW - 60
    b.poll_once()
    plans = [m for m in sent if m["t"] == "plan"]
    assert plans[-1]["plan"] == "unreported"
    sent.clear()
    acct.kind = "consumer"
    b.poll_if_changed()
    assert sent == [protocol.plan()]
